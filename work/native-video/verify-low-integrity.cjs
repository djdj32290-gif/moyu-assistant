// Verify the restricted-context failure without changing registry fixtures or labels.
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'outputs/点选缩放视频助手');
const version = JSON.parse(fs.readFileSync(path.join(root, 'src/manifest.json'))).version;
const home = path.join(__dirname, 'low-integrity-helper');
fs.mkdirSync(home, { recursive: true });
fs.copyFileSync(path.join(source, 'PointResizeVideo.exe'), path.join(home, 'PointResizeVideo.exe'));
const exe = path.join(home, 'PointResizeVideo.exe');
const options = { cwd: home, windowsHide: true, env: { ...process.env, POINT_RESIZE_TEST_MODE: '1', TEMP: home, TMP: home } };
const keys = ['HKCU\\Software\\Classes\\pointresize-video-test', ...['Google\\Chrome', 'Microsoft\\Edge'].map(x => 'HKCU\\Software\\' + x + '\\NativeMessagingHosts\\com.pointresize.video.test')];
const snapshot = () => keys.map(key => {
  const r = cp.spawnSync('reg.exe', ['query', key, '/s'], { windowsHide: true, encoding: 'utf8' });
  return { status: r.status, stdout: r.stdout };
});
const before = snapshot(), checks = [];
const run = args => cp.spawnSync(exe, args, { ...options, encoding: 'utf8' });
let result = run(['--prepare']);
assert.equal(result.status, 1);
let log = fs.readFileSync(path.join(home, 'data/last-error.txt'), 'utf8');
assert(log.includes('低完整性') && log.includes('S-1-16-4096'));
assert(!log.includes('请在正常 Windows 桌面运行'));
checks.push('Prepare reports actual Low integrity SID instead of recommending Explorer retry');
result = run(['--connect', 'pointresize-video-test://connect?extension=' + 'b'.repeat(32)]);
assert.equal(result.status, 1);
log = fs.readFileSync(path.join(home, 'data/last-error.txt'), 'utf8');
assert(log.includes('低完整性'));
const config = JSON.parse(fs.readFileSync(path.join(home, 'com.pointresize.video.test.json'), 'utf8'));
assert.deepEqual(config.allowed_origins, ['chrome-extension://' + 'b'.repeat(32) + '/']);
assert.deepEqual(snapshot(), before);
checks.push('Connect validates exact extension ID but does not change registration under Low integrity');
result = run(['--connect', 'https://example.com/connect?extension=' + 'b'.repeat(32)]);
assert.equal(result.status, 1);
assert(fs.readFileSync(path.join(home, 'data/last-error.txt'), 'utf8').includes('连接地址无效'));
checks.push('Invalid external connection URI remains rejected');
const payload = Buffer.from(JSON.stringify({ type: 'hello' })), length = Buffer.alloc(4);
length.writeUInt32LE(payload.length);
result = cp.spawnSync(exe, ['chrome-extension://' + 'b'.repeat(32) + '/'], { ...options, input: Buffer.concat([length, payload]) });
assert.equal(result.status, 0);
assert.equal(result.stdout.readUInt32LE(0), result.stdout.length - 4);
assert.deepEqual(JSON.parse(result.stdout.subarray(4)), { ok: true, protocol: 1, version, panel: true, canUninstall: false });
checks.push('Native hello protocol still replies and exits without opening a player');
const report = { timestamp: new Date().toISOString(), version, binarySHA256: crypto.createHash('sha256').update(fs.readFileSync(exe)).digest('hex'), checks, firstRunRegistration: 'BLOCKED: Low integrity; no fallback fixture, elevation, file-label or ACL changes attempted.', scope: 'Focused diagnostics and handshake only. Does not verify MSI installation.' };
fs.writeFileSync(path.join(__dirname, 'low-integrity-verification.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
